import random
import sys
from datetime import datetime
from enum import Enum
from pathlib import Path


class TermName(Enum):
    WINTER = 0
    SPRING = 1
    SUMMER = 2
    FALL = 3


semesters: list[TermName | None] = [
    (None if month == 0 else
     TermName.SPRING if month <= 5 else
     TermName.SUMMER if month <= 7 else
     TermName.FALL
     ) for month in range(13)
]

quarters: list[TermName | None] = [
    (None if month == 0 else
     TermName.WINTER if month <= 3 else
     TermName.SPRING if month <= 6 else
     TermName.SUMMER if month <= 9 else
     TermName.FALL
     ) for month in range(13)
]

terms: list[TermName | None] = semesters

BUFFER_SIZE_LOWER_BOUND = 16
BUFFER_SIZE_UPPER_BOUND = 36

STACK_OFFSET_LOWER_BOUND = 8
STACK_OFFSET_UPPER_BOUND = 64
STACK_ALIGNMENT = 16

gadgets = [
    'GENERATE_POINTER',
    'POP_TWO',
    'MOV1',
    'MOV2',
    'POP_ONE',
    'ADD_TO_SP',
]

paddings = [
    'PADDING_008_BYTES',
    'PADDING_016_BYTES',
    'PADDING_032_BYTES',
    'PADDING_064_BYTES',
    'PADDING_128_BYTES',
]

nops = [
    ['NOP', 'NOP_ALT'],
    ['NOP', 'NOP_ALT', 'EMPTY']
]


def generate_header(student_id: int, term: TermName, year: int) -> str:
    seed: int = ((student_id + term.value + year) ^ 0xA5A5A5A5) & 0xFFFFFFFF
    if seed == 0:
        seed = 0x1

    random_generator = random.Random(seed)
    random_generator.shuffle(gadgets)

    buffer_size: int = random_generator.randint(BUFFER_SIZE_LOWER_BOUND, BUFFER_SIZE_UPPER_BOUND)
    student_stack_offset: int = random_generator.randrange(STACK_OFFSET_LOWER_BOUND, STACK_OFFSET_UPPER_BOUND + 1,
                                                           STACK_ALIGNMENT)

    checkpoint_padding: list[str] = [random_generator.choice(paddings) for _ in range(7)]
    gadget_padding: list[str] = [random_generator.choice(paddings) for _ in range(6)]
    nop1: list[str] = [random_generator.choice(nops[0]) for _ in range(6)]
    nop2: list[str] = [random_generator.choice(nops[1]) for _ in range(6)]

    header = f'''\
/**************************************************************************//**
 *
 * @file randomization.h
 *
 * @author AUTO-GENERATED by generate_randomization.py
 *
 * @brief Student-specific customizations.
 *
 * Randomization seed 0x{seed:08X} computed using
 * student ID {student_id:08d} for {term.name} {year}
 *
 ******************************************************************************/

#ifndef RANDOMIZATION_H
#define RANDOMIZATION_H

#include <stddef.h>
#include "../target/code-offsets.h"
#include "../target/gadgets.h"

constexpr size_t BUFFER_SIZE = {buffer_size};
constexpr size_t STUDENT_STACK_OFFSET = {student_stack_offset};

#define CHECKPOINT_PADDING01    {checkpoint_padding[0]}
#define CHECKPOINT_PADDING02    {checkpoint_padding[1]}
#define CHECKPOINT_PADDING03    {checkpoint_padding[2]}
#define CHECKPOINT_PADDING04    {checkpoint_padding[3]}
#define CHECKPOINT_PADDING05    {checkpoint_padding[4]}
#define CHECKPOINT_PADDING06    {checkpoint_padding[5]}
#define CHECKPOINT_PADDING07    {checkpoint_padding[6]}

#define GADGET_PADDING01        {gadget_padding[0]}
#define GADGET_PADDING02        {gadget_padding[1]}
#define GADGET_PADDING03        {gadget_padding[2]}
#define GADGET_PADDING04        {gadget_padding[3]}
#define GADGET_PADDING05        {gadget_padding[4]}
#define GADGET_PADDING06        {gadget_padding[5]}

#define GADGET01                {gadgets[0]}
#define GADGET02                {gadgets[1]}
#define GADGET03                {gadgets[2]}
#define GADGET04                {gadgets[3]}
#define GADGET05                {gadgets[4]}
#define GADGET06                {gadgets[5]}

#define GADGET_NOP01_1          {nop1[0]}
#define GADGET_NOP02_1          {nop1[1]}
#define GADGET_NOP03_1          {nop1[2]}
#define GADGET_NOP04_1          {nop1[3]}
#define GADGET_NOP05_1          {nop1[4]}
#define GADGET_NOP06_1          {nop1[5]}

#define GADGET_NOP01_2          {nop2[0]}
#define GADGET_NOP02_2          {nop2[1]}
#define GADGET_NOP03_2          {nop2[2]}
#define GADGET_NOP04_2          {nop2[3]}
#define GADGET_NOP05_2          {nop2[4]}
#define GADGET_NOP06_2          {nop2[5]}

#endif // RANDOMIZATION_H
'''
    return header


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print('usage: generate_randomization.py <input student-id.txt> <output randomization.h>', file=sys.stderr)
        return 1

    student_id_path = Path(argv[1])
    text: str = student_id_path.read_text(encoding='utf-8').strip()
    if not text.isdigit():
        raise ValueError(f'{student_id_path} must contain only decimal digits (got {text!r})')
    student_id = int(text, 10)

    now = datetime.now()

    header = generate_header(student_id, terms[now.month], now.year)

    output_path = Path(argv[2])
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(header, encoding='utf-8')

    return 0


if __name__ == '__main__':
    main(sys.argv)
